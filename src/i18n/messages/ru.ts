/** Pluriel russe : 1 → forme1, 2-4 → forme2, 5+ → forme5 (avec les exceptions 11-14). */
function plRu(n: number, un: string, deux: string, cinq: string): string {
  const d10 = n % 10;
  const d100 = n % 100;
  if (d10 === 1 && d100 !== 11) return un;
  if (d10 >= 2 && d10 <= 4 && (d100 < 12 || d100 > 14)) return deux;
  return cinq;
}

